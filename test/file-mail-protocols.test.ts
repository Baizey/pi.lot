const pop3 = definition(Protocol.POP3);

function complete(bytes: Buffer, inspect: (bytes: Buffer) => ChannelProbe): void {
    for (let length = 0; length < bytes.length; length++) {
        assert.equal(inspect(bytes.subarray(0, length)).status, "incomplete", `fragment ${length}/${bytes.length}: ${bytes.toString("hex")}`);
    }
    assert.deepEqual(inspect(bytes), {status: "match", length: bytes.length});
    // Continuation is opaque after authorization; neither text nor binary parsers inspect it.
    assert.deepEqual(inspect(Buffer.concat([bytes, Buffer.from("\x00\nopaque continuation\r\n")])), {status: "match", length: bytes.length});
}

function hex(value: string): Buffer {
    return Buffer.from(value.replace(/\s/g, ""), "hex");
}

function changed(bytes: Buffer, offset: number, value: number, width = 1, littleEndian = false): Buffer {
    const copy = Buffer.from(bytes);
    if (littleEndian) copy.writeUIntLE(value, offset, width);
    else copy.writeUIntBE(value, offset, width);
    return copy;
}

