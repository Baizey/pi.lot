function definition(protocol: Protocol) {
    const found = fileMailProtocols.find((candidate) => candidate.protocol === protocol);
    assert.ok(found);
    return found;
}

const ftp = definition(Protocol.FTP);
const smb = definition(Protocol.SMB);
const nfs = definition(Protocol.NFS);
const ldap = definition(Protocol.LDAP);
