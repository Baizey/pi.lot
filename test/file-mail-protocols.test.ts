test("NFS RPC rejections are correlated terminal envelopes, not confirmation of an NFS service", () => {
    const terminal = nfs.isTerminalResponse;
    assert.ok(terminal);
    const replies = [nfsReply(Buffer.alloc(0), 1), nfsReply(Buffer.concat([u32(3), u32(4)]), 2),
        nfsReply(Buffer.alloc(0), 3), nfsReply(Buffer.alloc(0), 4), nfsReply(Buffer.alloc(0), 5),
        rpc(hex("123456780000000100000001000000000000000200000002")),
        rpc(hex("1234567800000001000000010000000100000001")),
        rpc(Buffer.concat([hex("12345678000000010000000000000001"), xdrOctets(hex("01020304")), u32(1)]))];
    for (const response of replies) {
        complete(response, (bytes) => nfs.inspectServer(bytes, NFS3_NULL_REQUEST));
        assert.equal(terminal(response, NFS3_NULL_REQUEST), true, response.toString("hex"));
        assert.equal(terminal(Buffer.concat([response, Buffer.from("opaque continuation")]), NFS3_NULL_REQUEST), true);
    }
    assert.equal(terminal(NFS3_NULL_RESPONSE, NFS3_NULL_REQUEST), false);
    const request = nfsCall(3, 1, xdrOctets(Buffer.from("file")));
    const deniedNfsOperation = nfsReply(u32(13)); // NFS3ERR_ACCES inside RPC SUCCESS still confirms NFS.
    complete(deniedNfsOperation, (bytes) => nfs.inspectServer(bytes, request));
    assert.equal(terminal(deniedNfsOperation, request), false);
    const compound = nfsCall(4, 1, Buffer.concat([u32(0), u32(0), u32(1), u32(24)]));
    const failedCompound = nfsReply(Buffer.concat([u32(10013), u32(0), u32(1), u32(24), u32(10013)]));
    complete(failedCompound, (bytes) => nfs.inspectServer(bytes, compound));
    assert.equal(terminal(failedCompound, compound), false);
    for (const response of [changed(NFS3_NULL_RESPONSE, 4, 0), changed(NFS3_NULL_RESPONSE, 8, 0, 4),
        changed(NFS3_NULL_RESPONSE, 12, 2, 4), changed(NFS3_NULL_RESPONSE, 24, 6, 4),
        changed(NFS3_NULL_RESPONSE, 20, 401, 4), nfsReply(u32(99), 1)]) {
        assert.equal(nfs.inspectServer(response, NFS3_NULL_REQUEST).status, "invalid");
    }
    assert.equal(nfs.inspectServer(changed(NFS3_NULL_RESPONSE, 4, 0).subarray(0, 5), NFS3_NULL_REQUEST).status, "invalid");
});

