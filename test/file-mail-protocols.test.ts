test("LDAP search scopes, booleans, filter structure/depth, and response attribute framing", () => {
    function search(filter: Buffer, scope = 0, bool = 0): Buffer {
        return ldapMessage(tlv(0x63, octets(""), tlv(10, Buffer.from([scope])), hex("0a0100020100020100"),
            tlv(1, Buffer.from([bool])), filter, tlv(0x30)));
    }
    const filters = [tlv(0xa0, tlv(0x87, Buffer.from("cn")), tlv(0xa3, octets("sn"), octets("Alice"))),
        tlv(0xa2, tlv(0x87, Buffer.from("uid"))), tlv(0xa4, octets("cn"), tlv(0x30, tlv(0x80, Buffer.from("A")), tlv(0x81, Buffer.from("li")), tlv(0x82, Buffer.from("e")))),
        tlv(0xa9, tlv(0x82, Buffer.from("cn")), tlv(0x83, Buffer.from("Alice")), hex("840100"))];
    for (const filter of filters) complete(search(filter), ldap.inspectClient);
    let deep = tlv(0x87, Buffer.from("cn"));
    for (let depth = 0; depth < 34; depth++) deep = tlv(0xa2, deep);
    for (const request of [search(tlv(0x87)), search(tlv(0xa0)), search(tlv(0xa2)), search(deep),
        search(tlv(0x87, Buffer.from("cn")), 3), search(tlv(0x87, Buffer.from("cn")), 0, 1),
        search(tlv(0xa3, octets("cn"))), search(tlv(0xa9, tlv(0x83, Buffer.from("value"))))]) {
        assert.equal(ldap.inspectClient(request).status, "invalid");
    }
    assert.equal(ldap.inspectServer(ldapMessage(tlv(0x64, octets(""), tlv(0x30, tlv(0x30, octets("cn"), tlv(0x30))))), LDAP_SEARCH).status, "invalid");
});

test("file/mail families do not confuse each other's complete envelopes or common other protocols", () => {
    const clients = [[smb, SMB2_REQUEST], [nfs, NFS3_NULL_REQUEST], [ldap, LDAP_BIND]] as const;
    for (const [owner, bytes] of clients) {
        for (const candidate of fileMailProtocols) {
            if (candidate !== owner) assert.equal(candidate.inspectClient(bytes).status, "invalid", `${owner.protocol} as ${candidate.protocol}`);
        }
    }
    const greetings = [[ftp, "220 (vsFTPd 3.0.5)\r\n"], [imap, "* OK IMAP4 ready\r\n"], [pop3, "+OK POP3 ready\r\n"]] as const;
    for (const [owner, greeting] of greetings) {
        for (const candidate of fileMailProtocols) {
            if (candidate !== owner) assert.equal(candidate.inspectServer(Buffer.from(greeting)).status, "invalid");
        }
    }
    for (const bytes of [Buffer.from("GET / HTTP/1.1\r\n"), Buffer.from("220 mail.example ESMTP ready\r\n"),
        Buffer.from("SSH-2.0-OpenSSH_9.0\r\n"), hex("160303000a00000000000000000000")]) {
        for (const candidate of fileMailProtocols) {
            assert.equal(candidate.inspectClient(bytes).status, "invalid", candidate.protocol);
            assert.equal(candidate.inspectServer(bytes).status, "invalid", candidate.protocol);
        }
    }
});
