test("NFSv3 AUTH_SYS GETATTR and NFSv4 COMPOUND including XDR binary newline", () => {
    // Conventional AUTH_SYS: timestamp, machine name, uid/gid, group array.
    const sys = Buffer.concat([u32(0x65000000), xdrOctets(Buffer.from("client")), u32(1000), u32(1000), u32(1), u32(1000)]);
    const auth = Buffer.concat([u32(1), xdrOctets(sys)]);
    const fileHandle = hex("010203040506070a1112131415161718");
    const request = nfsCall(3, 1, xdrOctets(fileHandle), auth);
    const attributes = hex(`00000001 000001a4 00000001 000003e8 000003e8
        0000000000000000 0000000000000000 00000000 00000000
        0000000000000001 0000000000000002
        0000000000000000 0000000000000000 0000000000000000`);
    complete(request, nfs.inspectClient);
    complete(nfsReply(Buffer.concat([u32(0), attributes])), (bytes) => nfs.inspectServer(bytes, request));
    const tag = xdrOctets(Buffer.from("tag\n"));
    // v4.0 PUTROOTFH (24), GETFH (10). For v4.1/v4.2 use session-establishing EXCHANGE_ID
    // (42), not file operations lacking the mandatory session SEQUENCE operation.
    // EXCHANGE_ID: RFC 8881 §18.35, https://www.rfc-editor.org/rfc/rfc8881#section-18.35
    for (const minor of [0, 1, 2]) {
        const operations = minor === 0 ? Buffer.concat([u32(2), u32(24), u32(10)])
            : Buffer.concat([u32(1), u32(42), hex("0123456789abcdef"), xdrOctets(Buffer.from("client")),
                u32(0), u32(0), u32(0)]); // flags=0, SP4_NONE, no implementation ID
        const results = minor === 0 ? Buffer.concat([u32(2), u32(24), u32(0), u32(10), u32(0), xdrOctets(fileHandle)])
            : Buffer.concat([u32(1), u32(42), u32(0), hex("0123456789abcdef"), u32(1), u32(0x10000),
                u32(0), hex("0000000000000001"), xdrOctets(Buffer.from("server")),
                xdrOctets(Buffer.from("scope")), u32(0)]);
        const compound = nfsCall(4, 1, Buffer.concat([tag, u32(minor), operations]));
        const result = nfsReply(Buffer.concat([u32(0), tag, results]));
        complete(compound, nfs.inspectClient);
        complete(result, (bytes) => nfs.inspectServer(bytes, compound));
        assert.equal(nfs.inspectServer(changed(result, 36, 0x58), compound).status, "invalid"); // echoed tag
        assert.equal(nfs.inspectServer(changed(result, 40, 3, 4), compound).status, "invalid"); // more results than calls
    }
});

